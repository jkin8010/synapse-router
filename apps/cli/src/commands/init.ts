// @synapse-router/cli — `synapse init` command
// Sets up SDK project structure for synapse-sdk integration

import { mkdir, writeFile } from "node:fs/promises";
import { join, resolve, isAbsolute } from "node:path";

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

interface InitOptions {
  provider?: string;
  outDir: string;
  withCicd: boolean;
}

// ---------------------------------------------------------------------------
// Help
// ---------------------------------------------------------------------------

export function printInitHelp(): void {
  console.log(HELP_INIT);
}

// ---------------------------------------------------------------------------
// Parse args
// ---------------------------------------------------------------------------

export function parseInitArgs(argv: string[]): InitOptions {
  const options: InitOptions = {
    outDir: "./synapse-sdk",
    withCicd: false,
  };

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--out-dir" && argv[i + 1]) {
      options.outDir = argv[++i];
    } else if (arg === "--provider" && argv[i + 1]) {
      options.provider = argv[++i];
    } else if (arg === "--with-cicd") {
      options.withCicd = true;
    }
  }

  return options;
}

// ---------------------------------------------------------------------------
// Main handler
// ---------------------------------------------------------------------------

export async function handleInitCommand(argv: string[]): Promise<void> {
  if (argv.includes("--help") || argv.includes("-h")) {
    printInitHelp();
    return;
  }

  const options = parseInitArgs(argv);
  const outDir = isAbsolute(options.outDir)
    ? options.outDir
    : resolve(process.cwd(), options.outDir);
  const configPath = resolve(process.cwd(), "synapse.json");

  // Header
  console.log("\nSynapse Init — Setting up SDK project");
  console.log(`  SDK output:  ${outDir}`);

  if (options.provider) {
    console.log(`  Provider:    ${options.provider}`);
  }
  if (options.withCicd) {
    console.log(`  CI/CD:       .github/workflows/synapse-evolve.yml`);
  }
  console.log("");

  // Create SDK output directory
  await mkdir(outDir, { recursive: true });

  // Write .gitkeep
  await writeFile(join(outDir, ".gitkeep"), "", "utf8");

  // Write README.md
  const readme = `# Synapse SDK

Auto-generated zero-dependency TypeScript SDK for provider APIs.

## Usage

Import the generated client for any configured provider:

\`\`\`typescript
import { OpenAIClient } from './synapse-sdk/openai/index.js';

const client = new OpenAIClient({
  apiKey: process.env.OPENAI_API_KEY!,
});

const result = await client.chat({
  messages: [{ role: 'user', content: 'Hello!' }],
  model: 'gpt-4',
});
\`\`\`

## Regenerate

\`\`\`bash
synapse evolve --out-dir ./synapse-sdk
\`\`\`

## Learn more

[synapse-router](https://github.com/useeclaw/synapse-router)
`;
  await writeFile(join(outDir, "README.md"), readme, "utf8");

  // Write synapse.json config
  const config: Record<string, unknown> = {
    version: "0.1.0",
    sdk_output_dir: options.outDir,
    generated_at: new Date().toISOString(),
  };

  if (options.provider) {
    config.default_provider = options.provider;
  }

  await writeFile(configPath, JSON.stringify(config, null, 2) + "\n", "utf8");

  // CI/CD workflow
  if (options.withCicd) {
    const githubDir = join(process.cwd(), ".github", "workflows");
    await mkdir(githubDir, { recursive: true });

    const workflow = `# Auto-generated by synapse init --with-cicd
# Scheduled Synapse SDK evolution with production profile data

name: Synapse SDK Evolution

on:
  schedule:
    - cron: '0 6 * * 1'   # Every Monday at 06:00 UTC
  workflow_dispatch:        # Manual trigger

env:
  SYNAPSE_SDK_DIR: ${JSON.stringify(options.outDir)}

jobs:
  evolve:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: 22

      - name: Install dependencies
        run: |
          npm install -g pnpm
          pnpm install

      - name: Pull production .synapse/ data
        run: git pull origin prod-data || echo "No prod-data branch found — skipping profile data"

      - name: Synapse Evolve
        run: npx synapse evolve --with-profile --out-dir $SYNAPSE_SDK_DIR

      - name: Verify generated SDK
        run: |
          if [ -d "$SYNAPSE_SDK_DIR" ]; then
            cd $SYNAPSE_SDK_DIR
            npx tsc --noEmit || echo "Type check warnings (non-blocking)"
          fi

      - name: Create Pull Request if changed
        uses: peter-evans/create-pull-request@v6
        with:
          token: \${{ secrets.GITHUB_TOKEN }}
          commit-message: "chore: auto-evolve Synapse SDK"
          title: "chore: auto-evolve Synapse SDK"
          body: |
            ## Automated SDK Evolution

            This PR was automatically generated by the Synapse SDK Evolution workflow.

            - **Trigger:** \`\${{ github.event_name }}\`
            - **Date:** \`\${{ github.event.repository.updated_at }}\`

            > Generated by [synapse-router](https://github.com/useeclaw/synapse-router)
          branch: auto/synapse-evolve
          delete-branch: true
`;

    await writeFile(join(githubDir, "synapse-evolve.yml"), workflow, "utf8");
  }

  // Summary
  console.log(`Created: ${outDir}/`);
  console.log(`  README.md`);
  console.log(`  .gitkeep`);
  if (options.withCicd) {
    console.log(`Created: .github/workflows/synapse-evolve.yml`);
  }
  console.log(`Created: ${configPath}`);
  console.log("");
  console.log("Next steps:");
  console.log(`  1. Add providers:  synapse pack add <provider>`);
  console.log(`  2. Generate SDK:   synapse evolve --out-dir ${options.outDir}`);
}
