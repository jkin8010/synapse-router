// @synapse-router/sdk-generator — Python code generator (skeleton, P2)

import type { PackData, GeneratedFile, FeatureEndpointMap } from "./generator.js";
import { featureIdToMethodName, buildFeatureEndpointMap } from "./generator.js";
import type { ProviderCard } from "@synapse-router/core";

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function toPascalCase(str: string): string {
  return str
    .replace(/([a-z])([A-Z])/g, '$1_$2')
    .split(/[_\s-]+/)
    .filter((part) => part.length > 0)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

function className(providerName: string): string {
  return `${toPascalCase(providerName)}Client`;
}

/** Build the endpoint path from feature_id, with DSL endpoint override. */
function featureIdToEndpoint(featureId: string, endpointMap?: FeatureEndpointMap): string {
  if (endpointMap?.has(featureId)) {
    return endpointMap.get(featureId)!;
  }
  const match = featureId.match(/_(?:post|get|put|patch|delete)_v\d+_(.+)$/);
  if (match) {
    return "/" + match[1].replace(/_/g, "/");
  }
  return "/" + featureId.replace(/_/g, "/");
}

// ---------------------------------------------------------------------------
// File generation
// ---------------------------------------------------------------------------

export function generatePython(packData: PackData): GeneratedFile[] {
  const { providerCard, providerId, providerName, baseUrl, dslDocuments } = packData;
  const clientClass = className(providerName);
  const now = new Date().toISOString().split("T")[0];
  const endpointMap = buildFeatureEndpointMap(dslDocuments);

  const files: GeneratedFile[] = [];

  // ---- __init__.py ----
  files.push({
    path: "__init__.py",
    content: generateInit(clientClass, providerName, providerId),
  });

  // ---- client.py ----
  files.push({
    path: "client.py",
    content: generateClient(providerCard, clientClass, baseUrl, providerId, providerName, now, endpointMap),
  });

  // ---- pyproject.toml ----
  files.push({
    path: "pyproject.toml",
    content: generatePyproject(providerId, providerName),
  });

  // ---- README.md ----
  files.push({
    path: "README.md",
    content: `# synapse-sdk-${providerId}\n\nAuto-generated SDK for ${providerName} API (Python).\n\n## Installation\n\n\`\`\`bash\npip install synapse-sdk-${providerId}\n\`\`\`\n\n## Usage\n\n\`\`\`python\nfrom synapse_sdk_${providerId} import ${clientClass}\n\nclient = ${clientClass}(api_key="your-api-key")\nresult = await client.chat(messages=[{"role": "user", "content": "Hello!"}], model="gpt-4")\n\`\`\`\n`,
  });

  return files;
}

function generateInit(clientClass: string, providerName: string, providerId: string): string {
  return `"""Auto-generated SDK for ${providerName} API"""

from .client import ${clientClass}

__all__ = ["${clientClass}"]
`;
}

function generateClient(
  providerCard: ProviderCard,
  clientClass: string,
  baseUrl: string,
  providerId: string,
  providerName: string,
  now: string,
  endpointMap?: FeatureEndpointMap,
): string {
  const lines: string[] = [];

  lines.push(`"""Auto-generated SDK for ${providerName} API"""`
  );
  lines.push(`# Generated by @synapse-router/sdk-generator at ${now}`);
  lines.push(`# Provider: ${providerId}`);
  lines.push("");
  lines.push("from typing import Any, Optional");
  lines.push("import httpx");
  lines.push("");
  lines.push("");

  // Class definition
  lines.push(`class ${clientClass}:`);
  lines.push(`    """${providerName} API Client (auto-generated)"""`);
  lines.push("");
  lines.push(`    def __init__(self, api_key: str, base_url: str = "${baseUrl}"):`);
  lines.push("        self.api_key = api_key");
  lines.push("        self.base_url = base_url");
  lines.push("        self._client = httpx.AsyncClient()");
  lines.push("");

  // Methods
  for (const feature of providerCard.features) {
    const methodName = featureIdToMethodName(feature.id);
    const endpoint = featureIdToEndpoint(feature.id, endpointMap);

    lines.push(`    async def ${methodName}(self, **kwargs: Any) -> dict[str, Any]:`);
    if (feature.description) {
      lines.push(`        """${feature.description}"""`);
    }
    lines.push("        response = await self._client.post(");
    lines.push(`            f"{self.base_url}${endpoint}",`);
    lines.push(`            headers={"Authorization": f"Bearer {self.api_key}"},`);
    lines.push("            json=kwargs,");
    lines.push("        )");
    lines.push("        response.raise_for_status()");
    lines.push("        return response.json()");
    lines.push("");
  }

  return lines.join("\n");
}

function generatePyproject(providerId: string, providerName: string): string {
  return `[project]
name = "synapse-sdk-${providerId}"
version = "1.0.0"
description = "Auto-generated SDK for ${providerName} API"
license = "Apache-2.0"
requires-python = ">=3.11"
dependencies = [
    "httpx>=0.27.0",
]
`;
}
