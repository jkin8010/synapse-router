// @synapse-router/sdk-generator — BillingTracker code generator

import type { GeneratedFile, PackData } from "./generator.js";
import { pricingFromProviderCard } from "@synapse-router/billing";
import type { PricingRule } from "@synapse-router/billing";

// ---------------------------------------------------------------------------
// BillingTracker generation — standalone zero-dependency TypeScript class
// ---------------------------------------------------------------------------

export function generateBillingTracker(packData: PackData): GeneratedFile {
  const features = packData.providerCard.features;
  const now = new Date().toISOString();

  const pricingMap: Record<string, PricingRule> = {};
  for (const feature of features) {
    pricingMap[feature.id] = pricingFromProviderCard(feature.pricing);
  }

  const lines: string[] = [];

  lines.push("// Auto-generated by @synapse-router/sdk-generator");
  lines.push(`// Provider: ${packData.providerId}`);
  lines.push(`// Generated at: ${now}`);
  lines.push("");

  // Inline simplified PricingRule — only the strategies and fields needed for tracking
  lines.push("// Simplified pricing rule for cost computation");
  lines.push("interface PricingRule {");
  lines.push("  strategy: 'perToken' | 'perUnit' | 'flat';");
  lines.push("  inputPrice?: number;");
  lines.push("  outputPrice?: number;");
  lines.push("  unitPrice?: number;");
  lines.push("}");
  lines.push("");

  // Inline pricing constants — serialized to numeric literals
  lines.push("const PRICING: Record<string, PricingRule> = {");
  for (const [featureId, rule] of Object.entries(pricingMap)) {
    const serialized: Record<string, unknown> = { strategy: rule.strategy };
    if (rule.inputPrice !== undefined) serialized.inputPrice = rule.inputPrice;
    if (rule.outputPrice !== undefined) serialized.outputPrice = rule.outputPrice;
    if (rule.unitPrice !== undefined) serialized.unitPrice = rule.unitPrice;
    lines.push(`  "${featureId}": ${JSON.stringify(serialized)},`);
  }
  lines.push("};");
  lines.push("");

  // BillingTracker class
  lines.push("class BillingTracker {");
  lines.push("  private usage: Record<string, { calls: number; totalCost: number }> = {};");
  lines.push("  private pricing: Record<string, PricingRule>;");
  lines.push("");
  lines.push("  constructor(config: { pricing: Record<string, PricingRule> }) {");
  lines.push("    this.pricing = config.pricing;");
  lines.push("  }");
  lines.push("");

  // record()
  lines.push("  record(featureId: string, usage?: { inputTokens?: number; outputTokens?: number }): void {");
  lines.push("    const rule = this.pricing[featureId];");
  lines.push("    if (!rule) return;");
  lines.push("    let cost = 0;");
  lines.push("    switch (rule.strategy) {");
  lines.push("      case 'perToken':");
  lines.push("        cost = ((usage?.inputTokens ?? 0) / 1000) * (rule.inputPrice ?? 0) +");
  lines.push("               ((usage?.outputTokens ?? 0) / 1000) * (rule.outputPrice ?? 0);");
  lines.push("        break;");
  lines.push("      case 'perUnit':");
  lines.push("        cost = rule.unitPrice ?? 0;");
  lines.push("        break;");
  lines.push("      case 'flat':");
  lines.push("        cost = 0;");
  lines.push("        break;");
  lines.push("    }");
  lines.push("    cost = Math.round(cost * 1_000_000) / 1_000_000;");
  lines.push("    if (!this.usage[featureId]) {");
  lines.push("      this.usage[featureId] = { calls: 0, totalCost: 0 };");
  lines.push("    }");
  lines.push("    this.usage[featureId].calls++;");
  lines.push("    this.usage[featureId].totalCost += cost;");
  lines.push("  }");
  lines.push("");

  // getUsage()
  lines.push("  getUsage(): Record<string, { calls: number; totalCost: number }> {");
  lines.push("    return structuredClone(this.usage);");
  lines.push("  }");
  lines.push("");

  // reset()
  lines.push("  reset(): void {");
  lines.push("    this.usage = {};");
  lines.push("  }");
  lines.push("}");
  lines.push("");

  // Named + default exports
  lines.push("export { BillingTracker, PRICING };");
  lines.push("export default new BillingTracker({ pricing: PRICING });");
  lines.push("");

  return { path: ".synapse/billing/tracker.ts", content: lines.join("\n") };
}

// ---------------------------------------------------------------------------
// Pricing snapshot — JSON file with provider-card pricing at generation time
// ---------------------------------------------------------------------------

export function generatePricingSnapshot(packData: PackData): GeneratedFile {
  const features = packData.providerCard.features;

  const pricingMap: Record<string, PricingRule> = {};
  for (const feature of features) {
    pricingMap[feature.id] = pricingFromProviderCard(feature.pricing);
  }

  const snapshot = {
    generatedAt: new Date().toISOString(),
    provider: packData.providerId,
    pricing: pricingMap,
  };

  return {
    path: ".synapse/billing/pricing.json",
    content: JSON.stringify(snapshot, null, 2) + "\n",
  };
}
